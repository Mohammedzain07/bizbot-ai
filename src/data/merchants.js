export const getPlatformSummary = () => {
  const total = MERCHANTS.reduce((s, m) => s + m.monthly_revenue, 0);
  const prev = MERCHANTS.reduce((s, m) => s + m.prev_month_revenue, 0);
  const growth = ((total - prev) / prev) * 100;
  const customers = MERCHANTS.reduce((s, m) => s + m.total_customers, 0);
  const avgRetention = MERCHANTS.reduce((s, m) => s + m.retention_rate, 0) / MERCHANTS.length;
  const atRisk = MERCHANTS.filter((m) => m.churn_risk_score >= 35).length;
  const thriving = MERCHANTS.filter((m) => m.health_status === "thriving").length;
  const vipInactive = MERCHANTS.reduce((s, m) => s + m.vip_inactive_30d, 0);

  return {
    total_merchants: MERCHANTS.length,
    total_monthly_revenue: total,
    revenue_growth_pct: parseFloat(growth.toFixed(1)),
    total_active_customers: customers,
    avg_retention_rate: parseFloat(avgRetention.toFixed(1)),
    merchants_at_risk: atRisk,
    merchants_thriving: thriving,
    vip_customers_inactive: vipInactive,
  };
};

